#!/usr/bin/env python3
"""Apply the judge-derived scorer/target fixes to the question records (idempotent).

Run AFTER apply_golds.py. Every change is guarded: a fact-regex swap or dot-escape is
applied ONLY if the gold prose still matches the new pattern, so no fix can break a
reference gold (which must score 100 by construction).

Fixes (from evals/golds-proposed/_judge_verdicts.json):
  - anchor loose fact regexes (kill bare-number / unescaped-dot false positives; Unicode dash)
  - escape literal dots in numeric fact regexes
  - demote unfetchable / historical must-have citations to nice-to-have
  - add citation_equivalents (accept an equal-valid alternate source)
  - add an 'overclaim' trap to april (fail an answer that claims clean 100% on-time completion)

    python3 evals/runners/apply_fixes.py
"""
from __future__ import annotations
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
QDIR = ROOT / "questions"
sys.path.insert(0, str(ROOT / "runners"))
import score as scorer  # noqa: E402

# fact-regex semantic swaps, keyed by the CURRENT match string
SWAPS = {
    "gpu": {"cute": r"sonic.?cute|gb200"},
    "july": {
        "0.8": r"xorl|MATH500|walked back",
        "preparation month": r"(preparation|bridge)[ -]month",
        "August 30": r"August 30|lands? in August|spill.{0,12}August",
    },
    "muon": {
        "Newton-Schulz": r"Newton.?Schulz",
        r"4\.7|21,962": r"4\.7|21,?962|21\.9k|1\.49\s*s",
    },
    "benchmarks": {
        "Table.9|table9|51": r"Table[ -]?9|table9",
        "4550|downstream.scaling": r"4550|downstream[ -]?scaling",
    },
    "h100-67b": {
        r"4\.75|1\.49": r"\b4\.75\s*%|4\.75\s*MFU|1\.49\s*s",
        "4 nodes|32 (H100|GPU)": r"4 nodes|four nodes|four-node|32 ?(H100|GPU)",
        r"121\.9|122|expert-weight|all-gather": r"121\.9|122 ?GiB|expert-weight.{0,20}re-?shard|Muon.{0,20}re-?shard",
    },
    "ablations": {
        "100k MMLU|100,000": r"100k|100,000",
        r"KL=0\.1|KL=0\.005": r"target-specific.{0,20}KL|KL=0\.1|KL=0\.005",
    },
    "classifier": {"distill": r"distill|generated by Claude|model[- ]generated|Claude[- ]derived"},
    "inference": {"Iris inference service": r"Iris[- ].{0,20}inference|inference service.{0,20}Iris|Iris inference"},
    "april": {"good enough": r"good enough[\s\S]{0,120}(4300|MFU)|(4300|MFU)[\s\S]{0,120}good enough"},
}
DEMOTE = {  # must-have -> nice-to-have (unfetchable-in-freeze / historical / not load-bearing)
    "inference": ["2237", "4401"],
    "h100-67b": ["7024"],
    "ablations": ["6712", "6713"],
}
EQUIV = {  # a must-have satisfied by any listed alternate citation
    "benchmarks": {"574": ["553"], "2779": ["3690"]},
    "ablations": {"6607": ["6602", "6603"], "6609": ["6602", "6603"]},
}
ADD_TRAP = {
    "april": {
        "name": "overclaim",
        "require": [r"slip|slipped|May|June|spill|not (fully|cleanly)|incomplete|missed|mixed|no formal|never.{0,20}complet"],
        "desc": "Do not claim a clean/on-time 100% completion; must acknowledge the tail (slipped into May/June, post-training mixed/missed, no formal 'complete' declaration).",
    },
}


def esc_dots(pat: str) -> str:
    """Escape every unescaped '.' that is NOT a quantified wildcard ('.{', '.*', '.+', '.?')
    and not inside a char class — turning literal-dot-as-wildcard numeric bugs into literals."""
    out, i, depth = [], 0, 0
    while i < len(pat):
        c = pat[i]
        if c == "\\":
            out.append(pat[i:i + 2]); i += 2; continue
        if c == "[":
            depth += 1
        elif c == "]" and depth:
            depth -= 1
        if c == "." and depth == 0 and (i + 1 >= len(pat) or pat[i + 1] not in "{*+?"):
            out.append(r"\.")
        else:
            out.append(c)
        i += 1
    return "".join(out)


def norm(c):
    return str(c).lstrip("#")


def main() -> None:
    for qid in ["gpu", "july", "april", "muon", "ablations", "classifier", "benchmarks", "h100-67b", "inference"]:
        qp = QDIR / f"{qid}.json"
        q = json.load(open(qp))
        gold = q["gold_prose"]
        applied, skipped = [], []

        # 1. semantic swaps (guarded: gold must still match)
        swaps = SWAPS.get(qid, {})
        swapped_ids = set()
        for f in q["facts"]["must_have"]:
            if f["match"] in swaps:
                new = swaps[f["match"]]
                if re.search(new, gold, re.I):
                    applied.append(f"swap f{f['id']}: {f['match']!r}->{new!r}")
                    f["match"] = new; swapped_ids.add(f["id"])
                else:
                    skipped.append(f"swap f{f['id']} ({f['match']!r}) — gold no longer matches new pattern")

        # 2. dot-escape the remaining numeric fact regexes (guarded)
        for f in q["facts"]["must_have"]:
            if f["id"] in swapped_ids:
                continue
            e = esc_dots(f["match"])
            if e != f["match"] and re.search(e, gold, re.I):
                applied.append(f"esc  f{f['id']}: {f['match']!r}->{e!r}")
                f["match"] = e

        # 3. demote must-have citations -> nice-to-have
        dem = set(norm(c) for c in DEMOTE.get(qid, []))
        if dem:
            mh = q["citations"]["must_have"]
            keep = [c for c in mh if norm(c) not in dem]
            moved = [c for c in mh if norm(c) in dem]
            q["citations"]["must_have"] = keep
            q["citations"]["nice_to_have"] = list(dict.fromkeys(q["citations"]["nice_to_have"] + moved))
            if moved:
                applied.append(f"demote must->nice: {moved}")

        # 4. citation equivalents
        if qid in EQUIV:
            q["citation_equivalents"] = EQUIV[qid]
            applied.append(f"equiv: {EQUIV[qid]}")

        # 5. add trap
        if qid in ADD_TRAP:
            t = ADD_TRAP[qid]
            q.setdefault("trap_checks", {})[t["name"]] = {"require": t["require"]}
            q.setdefault("traps", {})[t["name"]] = t["desc"]
            applied.append(f"trap +{t['name']}")

        json.dump(q, open(qp, "w"), indent=2)
        print(f"[{qid}] " + ("; ".join(applied) if applied else "no change"))
        for s in skipped:
            print(f"    ⚠ skipped {s}")

    # gold-consistency check: every gold must still score 100 in reference mode
    FREEZE = scorer.freeze_issue_set(*scorer.freeze_paths(ROOT))
    print("\n=== gold self-consistency (must be 100.0) ===")
    for qid in ["gpu", "july", "april", "muon", "ablations", "classifier", "benchmarks", "h100-67b", "inference"]:
        q = json.load(open(QDIR / f"{qid}.json"))
        g = scorer.score(q, q["gold_prose"], FREEZE, mode="reference")
        flag = "" if g["Q"] == 100.0 else "  <-- BROKEN, investigate"
        print(f"  {qid:11} gold Q={g['Q']:.1f}  (cite {g['Q_components']['cite_recall_MH']:.2f} "
              f"fact {g['Q_components']['fact_cov_MH']:.2f} trap {g['Q_components']['trap_pass']:.2f}){flag}")


if __name__ == "__main__":
    main()
